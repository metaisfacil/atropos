// applyLevelsAVX2 maps sixteen interleaved NRGBA bytes with float64 arithmetic
// matching the Go implementation, then restores the four alpha bytes.
TEXT ·applyLevelsAVX2(SB), NOSPLIT, $0-8
	MOVQ args+0(FP), BP
	MOVQ 0(BP), R8
	MOVQ 8(BP), CX
	VBROADCASTSD 16(BP), Y13
	VBROADCASTSD 24(BP), Y14
	VPXOR X15, X15, X15
	MOVQ $255, AX
	MOVD AX, X11
	VPBROADCASTD X11, X11
	LEAQ ·levelsAlphaMask<>(SB), AX
	VMOVDQU (AX), X10
	XORQ DI, DI

levels_avx2_loop:
	VMOVDQU (R8)(DI*1), X12

	VPMOVZXBD X12, X0
	VCVTDQ2PD X0, Y0
	VSUBPD Y13, Y0, Y0
	VMULPD Y14, Y0, Y0
	VCVTTPD2DQY Y0, X0
	VPMAXSD X15, X0, X0
	VPMINSD X11, X0, X0

	VPSRLDQ $4, X12, X1
	VPMOVZXBD X1, X1
	VCVTDQ2PD X1, Y1
	VSUBPD Y13, Y1, Y1
	VMULPD Y14, Y1, Y1
	VCVTTPD2DQY Y1, X1
	VPMAXSD X15, X1, X1
	VPMINSD X11, X1, X1

	VPSRLDQ $8, X12, X2
	VPMOVZXBD X2, X2
	VCVTDQ2PD X2, Y2
	VSUBPD Y13, Y2, Y2
	VMULPD Y14, Y2, Y2
	VCVTTPD2DQY Y2, X2
	VPMAXSD X15, X2, X2
	VPMINSD X11, X2, X2

	VPSRLDQ $12, X12, X3
	VPMOVZXBD X3, X3
	VCVTDQ2PD X3, Y3
	VSUBPD Y13, Y3, Y3
	VMULPD Y14, Y3, Y3
	VCVTTPD2DQY Y3, X3
	VPMAXSD X15, X3, X3
	VPMINSD X11, X3, X3

	VPACKUSDW X1, X0, X0
	VPACKUSDW X3, X2, X2
	VPACKUSWB X2, X0, X0
	VPBLENDVB X10, X12, X0, X0
	VMOVDQU X0, (R8)(DI*1)

	ADDQ $16, DI
	CMPQ DI, CX
	JL levels_avx2_loop
	VZEROUPPER
	RET

DATA ·levelsAlphaMask<>+0(SB)/8, $0xff000000ff000000
DATA ·levelsAlphaMask<>+8(SB)/8, $0xff000000ff000000
GLOBL ·levelsAlphaMask<>(SB), RODATA|NOPTR, $16

// grayscaleAccentAVX2 converts four NRGBA pixels to exact BT.601 luma while
// applying an optional saturating accent adjustment to RGB.
TEXT ·grayscaleAccentAVX2(SB), NOSPLIT, $0-8
	MOVQ args+0(FP), BP
	MOVQ 0(BP), R8
	MOVQ 8(BP), R9
	MOVQ 16(BP), CX
	MOVBLZX 24(BP), AX
	MOVD AX, X13
	VPBROADCASTB X13, X13
	MOVBLZX 25(BP), R10
	LEAQ ·grayCoefficients<>(SB), AX
	VMOVDQU (AX), Y14
	LEAQ ·grayGreenShuffle<>(SB), AX
	VMOVDQU (AX), X15
	MOVQ $32768, AX
	MOVD AX, X11
	VPBROADCASTD X11, X11
	VPXOR X10, X10, X10
	XORQ DI, DI
	XORQ DX, DX

gray_avx2_loop:
	VMOVDQU (R8)(DX*1), X0
	TESTQ R10, R10
	JNE gray_subtract
	VPADDUSB X13, X0, X0
	JMP gray_adjusted
gray_subtract:
	VPSUBUSB X13, X0, X0
gray_adjusted:
	VPMOVZXBW X0, Y1
	VPMADDWD Y14, Y1, Y1
	VPHADDD Y1, Y1, Y2
	VEXTRACTI128 $1, Y2, X3
	VPUNPCKLQDQ X3, X2, X2
	VPADDD X11, X2, X2
	VPSRAD $16, X2, X2

	VPSHUFB X15, X0, X4
	VPMOVZXBD X4, X4
	VPADDD X4, X2, X2
	VPACKUSDW X10, X2, X2
	VPACKUSWB X10, X2, X2
	VMOVD X2, (R9)(DI*1)

	ADDQ $4, DI
	ADDQ $16, DX
	CMPQ DI, CX
	JL gray_avx2_loop
	VZEROUPPER
	RET

DATA ·grayCoefficients<>+0(SB)/8, $0x00001d2f96464c8b
DATA ·grayCoefficients<>+8(SB)/8, $0x00001d2f96464c8b
DATA ·grayCoefficients<>+16(SB)/8, $0x00001d2f96464c8b
DATA ·grayCoefficients<>+24(SB)/8, $0x00001d2f96464c8b
GLOBL ·grayCoefficients<>(SB), RODATA|NOPTR, $32

DATA ·grayGreenShuffle<>+0(SB)/8, $0x808080800d090501
DATA ·grayGreenShuffle<>+8(SB)/8, $0x8080808080808080
GLOBL ·grayGreenShuffle<>(SB), RODATA|NOPTR, $16

// maskBlendAVX2 blends four NRGBA pixels against a constant RGB background.
TEXT ·maskBlendAVX2(SB), NOSPLIT, $0-8
	MOVQ args+0(FP), BP
	MOVQ 0(BP), R8
	MOVQ 8(BP), R9
	MOVQ 16(BP), R10
	MOVQ 24(BP), CX
	VBROADCASTSD 32(BP), Y11
	VBROADCASTSD 40(BP), Y12
	VBROADCASTSD 48(BP), Y13
	LEAQ ·maskBlendShuffle<>(SB), AX
	VMOVDQU 0(AX), X14
	VMOVDQU 16(AX), X15
	VMOVDQU 32(AX), X6
	LEAQ ·maskBlendOnes<>(SB), AX
	VMOVUPD (AX), Y10
	MOVQ $255, AX
	MOVD AX, X7
	VPBROADCASTD X7, X7
	XORQ DI, DI
	XORQ DX, DX

mask_blend_loop:
	VMOVDQU (R8)(DX*1), X0
	VMOVUPD (R10)(DI*8), Y8
	VSUBPD Y8, Y10, Y9

	VPSHUFB X14, X0, X1
	VPMOVZXBD X1, X1
	VCVTDQ2PD X1, Y1
	VMULPD Y8, Y1, Y1
	VMULPD Y9, Y11, Y2
	VADDPD Y2, Y1, Y1
	VCVTTPD2DQY Y1, X1

	VPSHUFB X15, X0, X2
	VPMOVZXBD X2, X2
	VCVTDQ2PD X2, Y2
	VMULPD Y8, Y2, Y2
	VMULPD Y9, Y12, Y3
	VADDPD Y3, Y2, Y2
	VCVTTPD2DQY Y2, X2

	VPSHUFB X6, X0, X3
	VPMOVZXBD X3, X3
	VCVTDQ2PD X3, Y3
	VMULPD Y8, Y3, Y3
	VMULPD Y9, Y13, Y4
	VADDPD Y4, Y3, Y3
	VCVTTPD2DQY Y3, X3

	VPUNPCKLDQ X2, X1, X4
	VPUNPCKHDQ X2, X1, X5
	VPUNPCKLDQ X7, X3, X0
	VPUNPCKHDQ X7, X3, X2
	VPUNPCKLQDQ X0, X4, X1
	VPUNPCKHQDQ X0, X4, X4
	VPUNPCKLQDQ X2, X5, X3
	VPUNPCKHQDQ X2, X5, X5
	VPXOR X0, X0, X0
	VPACKUSDW X0, X1, X1
	VPACKUSWB X0, X1, X1
	VPACKUSDW X0, X4, X4
	VPACKUSWB X0, X4, X4
	VPACKUSDW X0, X3, X3
	VPACKUSWB X0, X3, X3
	VPACKUSDW X0, X5, X5
	VPACKUSWB X0, X5, X5
	VMOVD X1, 0(R9)(DX*1)
	VMOVD X4, 4(R9)(DX*1)
	VMOVD X3, 8(R9)(DX*1)
	VMOVD X5, 12(R9)(DX*1)

	ADDQ $4, DI
	ADDQ $16, DX
	CMPQ DI, CX
	JL mask_blend_loop
	VZEROUPPER
	RET

DATA ·maskBlendShuffle<>+0(SB)/8, $0x808080800c080400
DATA ·maskBlendShuffle<>+8(SB)/8, $0x8080808080808080
DATA ·maskBlendShuffle<>+16(SB)/8, $0x808080800d090501
DATA ·maskBlendShuffle<>+24(SB)/8, $0x8080808080808080
DATA ·maskBlendShuffle<>+32(SB)/8, $0x808080800e0a0602
DATA ·maskBlendShuffle<>+40(SB)/8, $0x8080808080808080
