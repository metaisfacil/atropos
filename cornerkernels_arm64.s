#include "textflag.h"

// cornerSobelNEON evaluates sixteen adjacent Sobel pixels as two groups of
// eight widened uint16 lanes, producing exact signed int16 gradients.
TEXT ·cornerSobelNEON(SB), NOSPLIT, $0-8
	MOVD args+0(FP), R0
	MOVD 0(R0), R1
	MOVD 8(R0), R2
	MOVD 16(R0), R3
	MOVD 24(R0), R4
	MOVD 32(R0), R5
	MOVD 40(R0), R6
	MOVD $0, R7

sobel_neon_loop:
	ADD R7, R1, R10
	ADD R7, R2, R11
	ADD R7, R3, R12
	VLD1 (R10), [V0.B16]
	VLD1 (R11), [V1.B16]
	VLD1 (R12), [V2.B16]
	ADD $2, R10, R8
	VLD1 (R8), [V3.B16]
	ADD $2, R11, R8
	VLD1 (R8), [V4.B16]
	ADD $2, R12, R8
	VLD1 (R8), [V5.B16]
	ADD $1, R10, R8
	VLD1 (R8), [V6.B16]
	ADD $1, R12, R8
	VLD1 (R8), [V7.B16]

	// Low eight pixels.
	VUXTL V0.B8, V8.H8
	VUXTL V1.B8, V9.H8
	VUXTL V2.B8, V10.H8
	VUXTL V3.B8, V11.H8
	VUXTL V4.B8, V12.H8
	VUXTL V5.B8, V13.H8
	VUXTL V6.B8, V14.H8
	VUXTL V7.B8, V15.H8
	VADD V9.H8, V9.H8, V16.H8
	VADD V8.H8, V16.H8, V16.H8
	VADD V10.H8, V16.H8, V16.H8
	VADD V12.H8, V12.H8, V17.H8
	VADD V11.H8, V17.H8, V17.H8
	VADD V13.H8, V17.H8, V17.H8
	VSUB V16.H8, V17.H8, V18.H8
	VADD V14.H8, V14.H8, V19.H8
	VADD V8.H8, V19.H8, V19.H8
	VADD V11.H8, V19.H8, V19.H8
	VADD V15.H8, V15.H8, V20.H8
	VADD V10.H8, V20.H8, V20.H8
	VADD V13.H8, V20.H8, V20.H8
	VSUB V19.H8, V20.H8, V21.H8
	LSL $1, R7, R8
	ADD R8, R4, R9
	VST1 [V18.H8], (R9)
	ADD R8, R5, R9
	VST1 [V21.H8], (R9)

	// High eight pixels.
	VUXTL2 V0.B16, V8.H8
	VUXTL2 V1.B16, V9.H8
	VUXTL2 V2.B16, V10.H8
	VUXTL2 V3.B16, V11.H8
	VUXTL2 V4.B16, V12.H8
	VUXTL2 V5.B16, V13.H8
	VUXTL2 V6.B16, V14.H8
	VUXTL2 V7.B16, V15.H8
	VADD V9.H8, V9.H8, V16.H8
	VADD V8.H8, V16.H8, V16.H8
	VADD V10.H8, V16.H8, V16.H8
	VADD V12.H8, V12.H8, V17.H8
	VADD V11.H8, V17.H8, V17.H8
	VADD V13.H8, V17.H8, V17.H8
	VSUB V16.H8, V17.H8, V18.H8
	VADD V14.H8, V14.H8, V19.H8
	VADD V8.H8, V19.H8, V19.H8
	VADD V11.H8, V19.H8, V19.H8
	VADD V15.H8, V15.H8, V20.H8
	VADD V10.H8, V20.H8, V20.H8
	VADD V13.H8, V20.H8, V20.H8
	VSUB V19.H8, V20.H8, V21.H8
	ADD $16, R9, R9
	VST1 [V21.H8], (R9)
	ADD R8, R4, R9
	ADD $16, R9, R9
	VST1 [V18.H8], (R9)

	ADD $16, R7, R7
	CMP R6, R7
	BLT sobel_neon_loop
	RET
